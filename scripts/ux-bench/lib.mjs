import { execFileSync } from 'node:child_process'

/** Arms compared by default. `D` resolves to HEAD when the build is prepared. */
export const ARMS = {
  A: { label: 'old module', ref: '23ca506' },
  D: { label: 'new module', ref: 'HEAD' },
}

export const BRIEFS = ['dashboard', 'landing', 'explainer']

/** List prices per 1M tokens for opencode-go/deepseek-v4.1-flash. */
export const PRICES = { input: 0.15, output: 0.6, cacheRead: 0.003 }

export const ROUTE = { provider: 'opencode-go', model: 'deepseek-v4.1-flash' }

/**
 * Off in every arm. Each one either spends on a second model (advisor, evo,
 * classifier), or carries state between runs (munin, agentmem), or is unrelated
 * surface that could change what the model does.
 */
export const DISABLED_MODULES = ['a2a', 'advisor', 'agentmem', 'classifier', 'cron', 'evo', 'gh', 'munin', 'notebooklm']

const UI_FILE = /\.(html|css|scss|tsx|jsx|vue|svelte)\b/
const WRITE_TOOLS = new Set(['write', 'edit', 'apply_patch'])
const VERDICT = /UX (?:runtime )?audit: (PASS|FAIL|INCOMPLETE)/
const DIRECTION = /^\W*Direction:/m

/** Same settings for every arm: the owner's tool surface, strict mode, no side channels. */
export function benchSettings(base) {
  const settings = structuredClone(base ?? {})
  settings.ux = { ...settings.ux, mode: 'strict' }
  settings.disabled = [...DISABLED_MODULES]
  return settings
}

