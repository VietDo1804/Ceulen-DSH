import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parseRulesFile, composeRulesBlock } from '../../lib/vendor/ceulen/rules/rules.js';
const source = '/home/vietdo/.dsh/ceulen/RULES.md';
const rules = parseRulesFile(readFileSync(process.argv[2] || source, 'utf8'), source);
const before = parseRulesFile(readFileSync(new URL('./RULES.before.md', import.meta.url), 'utf8'), source);
const sticky = rules.filter(r => r.sticky);
const guards = rules.filter(r => r.guard);
const rulebook = rules.filter(r => r.description && !r.guard);
const counted = sticky.reduce((n, r) => n + `### ${r.name} (${source})\n${r.body}\n`.length, 0);
const block = composeRulesBlock({files:[source],sources:[],rules,sticky,guards,rulebook}, process.cwd());
assert.equal(sticky.length, 8);
assert.equal(guards.length, 3);
assert.equal(rulebook.length, 1);
assert.ok(counted <= 4000, `${counted} > 4000`);
assert.ok(!block.includes('STICKY RULES TRUNCATED'));
for (const r of [...guards,...rulebook]) assert.deepEqual(r, before.find(b => b.name === r.name));
for (const r of sticky) assert.ok(block.includes(`### ${r.name} (`));
for (const phrase of ['consecutive provider', 'substantial rereading', 'routine confirmation', 'current repo state', 'never reference files outside it']) assert.ok(block.includes(phrase), `Missing condition: ${phrase}`);
console.log(JSON.stringify({sticky:sticky.length,guards:guards.length,rulebook:rulebook.length,counted,remaining:4000-counted,noOmissions:true,unchangedGuardsAndRulebook:true}));
